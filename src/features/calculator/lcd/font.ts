const build = (src: Record<string, string>) => {
  const out: Record<string, Glyph> = {};
  for (const [k, v] of Object.entries(src)) {
    const rows = v.split(" ");
    out[k] = { w: rows[0].length, rows };
  }
  return out;
};

export const FONT = build(NORMAL);
export const FONT_SMALL = build(SMALL);
export const FONT_MENU = build(MENU);
export const FONT_TINY = build(TINY);

/** Multi-code-point sequences that are drawn as one glyph or a fixed glyph run. */
const SEQS: [string, string[]][] = [
  ["▸n/d◂▸Un/d", ["▸", "n/d", "◂▸", "U", "n/d"]],
  ["▸F◂▸d", ["▸", "F", "◂▸", "d"]],
  ["◂▸", ["◂▸"]],
  ["⁻¹", ["⁻¹"]],
  ["x̄", ["x̄"]],
];

/** Split text into glyph keys. */
export function glyphKeys(s: string): string[] {
  const out: string[] = [];
  let i = 0;
  outer: while (i < s.length) {
    for (const [seq, keys] of SEQS) {
      if (s.startsWith(seq, i)) {
        out.push(...keys);
        i += seq.length;
        continue outer;
      }
    }
    const cp = s.codePointAt(i)!;
    const ch = String.fromCodePoint(cp);
    out.push(ch);
    i += ch.length;
  }
  return out;
}

const shrink = (g: Glyph, rows: number[], cols: number[]): Glyph => ({
  w: cols.length,
  rows: rows.map((r) => cols.map((c) => g.rows[r]?.[c] ?? ".").join("")),
});

const derived = new Map<string, Glyph>();

/** Glyph for a font: n normal 5×7, s small 5×5, m menu 4×5. Missing small/menu glyphs are shrunk from the normal font. */
export function glyph(key: string, font: "n" | "s" | "m" = "n"): Glyph {
  const base = FONT[key] ?? FONT["?"];
  if (font === "n") return base;
  const table = font === "s" ? FONT_SMALL : FONT_MENU;
  if (table[key]) return table[key];
  const id = font + key;
  if (!derived.has(id)) {
    const top = base.rows.length > 7 ? 2 : 0;
    const rows = top ? [2, 3, 4, 5, 7] : [0, 1, 3, 5, 6];
    const cols = base.w === 5 ? (font === "s" ? [0, 1, 2, 3, 4] : [0, 1, 3, 4]) : [...Array(base.w).keys()];
    derived.set(id, shrink(base, rows, cols));
  }
  return derived.get(id)!;
}
